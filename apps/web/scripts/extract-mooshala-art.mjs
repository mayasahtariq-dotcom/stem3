// Extracts the Mooshala prototype's sticker icons and Golu cow poses from
// docs/design/mooshala-code.md into src/components/ui/art.generated.ts, so the
// web app draws the same illustrated art as the Android app (never emoji).
// Run: node scripts/extract-mooshala-art.mjs
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const md = readFileSync(new URL("../../../docs/design/mooshala-code.md", import.meta.url), "utf8");
const grab = (start, endRe) => {
  const i = md.indexOf(start);
  if (i < 0) throw new Error(`missing ${start}`);
  const rest = md.slice(i);
  const m = rest.match(endRe);
  return rest.slice(0, m.index + m[0].length);
};
const iconsSrc = grab("const ICONS=", /\n\}\}\)\(\);/);
const cowSrc = grab("const ALIAS=", /\n  return `<svg class="cow[\s\S]*?`;\n\}/);

const ctx = {};
vm.createContext(ctx);
vm.runInContext(`${iconsSrc}\n${cowSrc}\nthis.ICONS=ICONS; this.cow=cow;`, ctx);

const skip = new Set(["cowface"]);
const icons = Object.fromEntries(Object.entries(ctx.ICONS).filter(([k]) => !skip.has(k)));

const MOODS = ["wave", "thumbs", "question", "sad", "sleep", "heart", "cool"];
const cows = {};
for (const mood of MOODS) {
  let svg = ctx.cow(mood);
  const idMatch = svg.match(/id="(c\d+)h"/);
  svg = svg.replaceAll(`id="${idMatch[1]}`, 'id="__ID__').replaceAll(`#${idMatch[1]}`, "#__ID__");
  // Keep only the inner markup; the React component renders the <svg> element.
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  cows[mood] = inner.replace(/\s*\n\s*/g, "");
}

const out = `// Generated by scripts/extract-mooshala-art.mjs from docs/design/mooshala-code.md. Do not edit.
export const STICKER_ICONS = ${JSON.stringify(icons, null, 1)} as const;
export type StickerIconName = keyof typeof STICKER_ICONS;

export const COW_VIEWBOX = "-14 -14 228 248";
/** Inner SVG markup per pose; "__ID__" is replaced with a unique id per instance. */
export const COW_POSES = ${JSON.stringify(cows, null, 1)} as const;
export type CowPose = keyof typeof COW_POSES;
`;
writeFileSync(new URL("../src/components/ui/art.generated.ts", import.meta.url), out);
console.log(`icons: ${Object.keys(icons).length}, poses: ${MOODS.join(", ")}`);
